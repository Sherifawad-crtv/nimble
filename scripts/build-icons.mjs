const resolve = (name) => {
  if (set.icons[name]) return set.icons[name];
  const alias = set.aliases?.[name];
  if (alias) return resolve(alias.parent);
  throw new Error(`Solar icon not found: ${name}`);
};

const entries = Object.entries(MAP).map(([key, solar]) => {
  const icon = resolve(solar);
  if ((icon.width ?? set.width) !== 24 || (icon.height ?? set.height) !== 24) throw new Error(`${solar} is not 24x24`);
  return `  ${JSON.stringify(key)}: ${JSON.stringify(icon.body)},`;
});

writeFileSync(
  'src/design/solar-icons.ts',
  `// Generated by scripts/build-icons.mjs from @iconify-json/solar. Do not edit.\n// Solar icon set by 480 Design, licensed CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/).\nexport const SOLAR_ICONS: Record<string, string> = {\n${entries.join('\n')}\n};\n`,
);
